"""List the third-party packages Harnis runs with, and their licenses.

Walks the runtime dependencies of the installed `harnis` distribution (not the
dev, docs or test tools) in the current environment and writes a Markdown
table. Standard library only.

    python scripts/third_party_licenses.py                 # print
    python scripts/third_party_licenses.py -o THIRD_PARTY_LICENSES.md

The versions are the ones installed where it runs; the release workflow
regenerates the file for the exact versions of each release.
"""
from __future__ import annotations

import argparse
import re
import sys
from importlib import metadata

HEADER = """# Third-party licenses

Harnis is licensed under the Apache License 2.0. It runs with the packages
below, each under its own license. This list covers the Python runtime
dependencies of the `harnis` package{versions_note}; the container images
also contain their base image's system packages (Debian) and Python itself.

Harnis is provided as is. Users are responsible for complying with the
licenses of everything they run with it.

Generated by `scripts/third_party_licenses.py`.

| Package | Version | License | Home page |
|---|---|---|---|
"""

_CLASSIFIER = re.compile(r"^License :: (?:OSI Approved :: )?(.+)$")


def _name(req: str) -> str | None:
    """Distribution name of a requirement, or None when it only applies
    through an extra or a marker that is false here."""
    m = re.match(r"\s*([A-Za-z0-9][A-Za-z0-9._\-]*)\s*(\[[^\]]*\])?([^;]*)(;(.*))?$", req)
    if not m:
        return None
    marker = (m.group(5) or "").strip()
    if marker:
        if "extra" in marker:
            return None
        try:
            from packaging.markers import Marker  # usually present; harmless if not

            if not Marker(marker).evaluate():
                return None
        except Exception:  # noqa: BLE001
            pass
    return m.group(1)


def _extras(req: str) -> list[str]:
    m = re.match(r"\s*[A-Za-z0-9][A-Za-z0-9._\-]*\s*\[([^\]]*)\]", req)
    return [e.strip() for e in m.group(1).split(",")] if m else []


def _requires(dist: metadata.Distribution, extras: list[str]) -> list[str]:
    out = []
    for req in dist.requires or []:
        name = _name(req)
        if name:
            out.append(req)
            continue
        # Requirements that apply only through one of the requested extras.
        for extra in extras:
            if re.search(r"extra\s*==\s*['\"]" + re.escape(extra) + r"['\"]", req):
                base = req.split(";", 1)[0]
                out.append(base)
    return out


def license_of(dist: metadata.Distribution) -> str:
    md = dist.metadata
    expr = md.get("License-Expression")
    if expr:
        return expr.strip()
    classifiers = [_CLASSIFIER.match(c).group(1) for c in md.get_all("Classifier") or [] if _CLASSIFIER.match(c)]
    lic = (md.get("License") or "").strip()
    if lic and "\n" not in lic and len(lic) <= 80 and lic.upper() != "UNKNOWN":
        return lic
    if classifiers:
        return "; ".join(dict.fromkeys(classifiers))
    return "see the package"


def home_of(dist: metadata.Distribution) -> str:
    md = dist.metadata
    if md.get("Home-page"):
        return md["Home-page"].strip()
    for url in md.get_all("Project-URL") or []:
        label, _, link = url.partition(",")
        if label.strip().lower() in ("homepage", "home", "source", "repository", "source code"):
            return link.strip()
    urls = md.get_all("Project-URL") or []
    return urls[0].partition(",")[2].strip() if urls else ""


def collect(root: str = "harnis") -> list[metadata.Distribution]:
    seen: dict[str, metadata.Distribution] = {}
    todo = [(root, [])]
    while todo:
        name, extras = todo.pop()
        key = re.sub(r"[-_.]+", "-", name).lower()
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            continue
        first = key not in seen
        seen.setdefault(key, dist)
        if first or extras:
            for req in _requires(dist, extras):
                dep = _name(req.split(";", 1)[0])
                if dep:
                    todo.append((dep, _extras(req)))
    seen.pop(re.sub(r"[-_.]+", "-", root).lower(), None)
    return sorted(seen.values(), key=lambda d: d.metadata["Name"].lower())


def render(dists: list[metadata.Distribution], versions_note: str = "") -> str:
    rows = []
    for d in dists:
        home = home_of(d)
        label = re.sub(r"^https?://(www\.)?", "", home).rstrip("/")
        cell = f"[{label}]({home})" if home.startswith("http") else home
        lic = license_of(d).replace("|", "\\|")
        rows.append(f"| {d.metadata['Name']} | {d.version} | {lic} | {cell} |")
    return HEADER.format(versions_note=versions_note) + "\n".join(rows) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("-o", "--output", help="write here instead of printing")
    ap.add_argument("--for-version", help="note the Harnis version the list was made for")
    a = ap.parse_args(argv)
    try:
        metadata.distribution("harnis")
    except metadata.PackageNotFoundError:
        sys.exit("harnis is not installed in this environment (pip install . or pip install harnis)")
    note = f", as installed with Harnis {a.for_version}" if a.for_version else ""
    text = render(collect(), note)
    if a.output:
        with open(a.output, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"wrote {a.output} ({text.count(chr(10)) - HEADER.count(chr(10))} packages)")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
